"""Make a double-clickable "Sell Anything.app" (macOS) that runs scripts/play.py.

    python3 scripts/make_mac_app.py      # writes build/Sell Anything.app

The app records the absolute paths of this checkout and of the Python running this script (the one
with torch installed), because an app opened from Finder doesn't get the terminal's PATH. So it is
made per machine and lives in build/, which git ignores. If the game can't start, a dialog says why
and where the log is. Run it again after moving the checkout or switching Python.
"""

from __future__ import annotations

import plistlib
import shlex
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / "build" / "Sell Anything.app"
LOG = ROOT / "build" / "app.log"
SPRITE = ROOT / "game" / "assets" / "characters" / "look01" / "look01_win.png"


def make_icon(resources: Path) -> None:
    """A buyer from the game, scaled up pixel-for-pixel, on a rounded light square."""
    frame = Image.open(SPRITE).crop((5 * 64, 0, 6 * 64, 64))           # the win pose's last frame
    base = Image.new("RGBA", (1024, 1024), (0, 0, 0, 0))
    plate = Image.new("RGBA", (880, 880), (243, 240, 232, 255))
    mask = Image.new("L", (880, 880), 0)
    from PIL import ImageDraw
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, 879, 879], radius=190, fill=255)
    base.paste(plate, (72, 72), mask)
    figure = frame.resize((768, 768), Image.NEAREST)
    base.alpha_composite(figure, (128, 96))
    with tempfile.TemporaryDirectory() as tmp:
        iconset = Path(tmp) / "AppIcon.iconset"
        iconset.mkdir()
        for size in (16, 32, 128, 256, 512):
            base.resize((size, size), Image.LANCZOS).save(iconset / f"icon_{size}x{size}.png")
            base.resize((size * 2, size * 2), Image.LANCZOS).save(iconset / f"icon_{size}x{size}@2x.png")
        subprocess.run(["iconutil", "-c", "icns", str(iconset), "-o", str(resources / "AppIcon.icns")], check=True)


def main() -> int:
    if sys.platform != "darwin":
        print("This makes a macOS app; elsewhere run: python3 scripts/play.py")
        return 1
    if APP.exists():
        shutil.rmtree(APP)
    macos, resources = APP / "Contents" / "MacOS", APP / "Contents" / "Resources"
    macos.mkdir(parents=True)
    resources.mkdir()

    launcher = macos / "sell-anything"
    play, python, log = (shlex.quote(str(p)) for p in (ROOT / "scripts" / "play.py", Path(sys.executable), LOG))
    launcher.write_text(f"""#!/bin/bash
# Generated by scripts/make_mac_app.py
{python} {play} "$@" > {log} 2>&1
status=$?
if [ $status -ne 0 ]; then
  osascript -e 'display dialog "Sell Anything could not start (exit '"$status"').\\n\\nDetails are in {LOG}" with title "Sell Anything" buttons {{"OK"}} with icon caution'
fi
""")
    launcher.chmod(0o755)

    with open(APP / "Contents" / "Info.plist", "wb") as f:
        plistlib.dump({
            "CFBundleName": "Sell Anything",
            "CFBundleDisplayName": "Sell Anything",
            "CFBundleIdentifier": "io.github.alina0607.sellanything",
            "CFBundleExecutable": "sell-anything",
            "CFBundleIconFile": "AppIcon",
            "CFBundlePackageType": "APPL",
            "CFBundleShortVersionString": "0.1.0",
            "LSMinimumSystemVersion": "12.0",
            "NSHighResolutionCapable": True,
        }, f)
    make_icon(resources)
    print(f"{APP.relative_to(ROOT)} → runs {Path(sys.executable)} scripts/play.py (log: {LOG.relative_to(ROOT)})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
