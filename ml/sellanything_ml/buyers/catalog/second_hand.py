def hours(noun: str, low: str, mid: str, high: str) -> dict:
    return attr(f"How many hours are on the {noun}?",
                opt("low", low, 1.4, condition=2, performance=1),
                opt("mid", mid, 1.0),
                opt("high", high, 0.6, condition=-2, low_maintenance=-1))


