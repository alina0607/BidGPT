"""Build buyer data v6: ask / react / refuse examples plus the new `parse` task
(docs/design-v2.md §6.3, §6.3d, §6.6).

    python -m sellanything_ml.buyers.datagen --out data/processed/buyers_v6_raw
    python -m sellanything_ml.buyers.augment --src data/processed/buyers_v6_raw --out data/processed/buyers_v6_base
    python -m sellanything_ml.datagen.build          # -> ml/data/processed/buyers_v6/

The ask / react / refuse examples are v5's, regenerated by the same engine with one change: a
condition reason about health, freshness or an animal's age has its own words (buyers/phrases.py
topic()). Every label (Δ, option, attribute, who speaks) is identical to v5's; 10.08% of the lines
differ, only in those reasons and in later prompts that quote them.

`parse` teaches the model which option a typed answer means. Its text comes from teacher-written
player answers (raw/teacher_gen/v6/batches/parse), and only answers a blind reviewer mapped to the
writer's target with high confidence are used (check.verdict == "accepted"). The reviews are round 2
(reviews/parse_r2, datagen/blind.py): round 1 could look up the targets and is not used. Labels never come from
the text: the target is the option the request asked for. Everything is rebuilt from the raw files
by this one command; the raw files are never changed.

Splits (fixed before any training, by hashes of ids, so a rebuild gives the same split):
  - items in item_splits.json's held-out lists      -> test_heldout   (items never trained on)
  - other items: one answer in 8 of each option     -> test_seen      (phrasings never trained on)
                 one in 20 of the rest              -> val
                 the rest                           -> train
Each example lists the options in a shuffled order, so the answer letter carries no position habit.
Two kinds of examples are added by code:
  - typos: a copy of the answer with one or two typing slips (TYPO_SHARE of answers, all splits; the
    test copies are marked so typo accuracy is reported separately);
  - "none": an answer written for another attribute of the same item, asked against this one
    (NONE_SHARE of the examples), so the model can say it cannot tell. Answers sharing a content
    word with this attribute's options are not used, since they may answer it after all.
"""

from __future__ import annotations

import hashlib
import json
import random
import re
import shutil
from collections import Counter, defaultdict

from ..buyers import format as fmt
from ..buyers.schema import DATA_DIR, load_items
from .check import answers, read_reviews, verdict

OUT_DIR = DATA_DIR / "processed" / "buyers_v6"
BASE_DIR = DATA_DIR / "processed" / "buyers_v6_base"     # ask / react / refuse, from buyers.datagen + augment
TYPO_SHARE = 0.35
NONE_SHARE = 0.12
SEED = 6


def _h(text: str) -> int:
    return int(hashlib.sha256(text.encode()).hexdigest()[:8], 16)


def split_of(answer_id: str, item_split: str) -> str:
    if item_split == "heldout":
        return "test_heldout"
    if _h(answer_id) % 8 == 0:
        return "test_seen"
    return "val" if _h("val" + answer_id) % 20 == 0 else "train"


KEYBOARD = {c: n for row in ("qwertyuiop", "asdfghjkl", "zxcvbnm") for i, c in enumerate(row)
            for n in [row[max(0, i - 1):i] + row[i + 1:i + 2]]}


def typo(text: str, rng: random.Random) -> str:
    """One or two slips in words of 4+ letters: a dropped, doubled, swapped or neighbouring key."""
    words = text.split(" ")
    spots = [i for i, w in enumerate(words) if sum(c.isalpha() for c in w) >= 4]
    if not spots:
        return text
    for i in rng.sample(spots, min(len(spots), rng.choice((1, 1, 2)))):
        w = words[i]
        letters = [j for j, c in enumerate(w) if c.isalpha()]
        j = rng.choice(letters[1:]) if len(letters) > 1 else letters[0]
        kind = rng.choice(("drop", "double", "swap", "near"))
        if kind == "drop":
            w = w[:j] + w[j + 1:]
        elif kind == "double":
            w = w[:j] + w[j] + w[j:]
        elif kind == "swap" and j + 1 < len(w) and w[j + 1].isalpha():
            w = w[:j] + w[j + 1] + w[j] + w[j + 2:]
        else:
            near = KEYBOARD.get(w[j].lower(), "")
            if near:
                w = w[:j] + rng.choice(near) + w[j + 1:]
        words[i] = w
    return " ".join(words)


def _content(text: str) -> set[str]:
    return {w for w in re.findall(r"[a-z]+", text.lower()) if len(w) >= 4 and w not in fmt.FUNCTION_WORDS}


def example(item, attr, said: str, target_id: str | None, rng: random.Random, **extra) -> dict:
    options = list(attr.options)
    rng.shuffle(options)
    index = None if target_id is None else [o.id for o in options].index(target_id)
    return {"task": "parse", "item": item.key, "attr": attr.name, "option": target_id, "said": said,
            "order": [o.id for o in options], **extra,
            "prompt": fmt.parse_prompt(item.noun, attr.question, [o.answer for o in options], said),
            "target": fmt.parse_target(index)}


def _answer_examples(rows, reviews, items, rng, stats):
    """Accepted answers as examples (plus their typo copies), by split; and the accepted answers by item."""
    by_split: dict[str, list[dict]] = defaultdict(list)
    accepted_by_item = defaultdict(list)
    for r in rows:
        q = r["request"]
        v = verdict(reviews.get(r["answer_id"]), q["target"])
        stats[f"verdict: {v}"] += 1
        if v != "accepted":
            continue
        item, attr = items[q["item"]], items[q["item"]].attributes[q["attribute"]]
        split = split_of(r["answer_id"], q["split"])
        accepted_by_item[q["item"]].append((r, split))
        by_split[split].append(example(item, attr, r["text"], q["target"], rng, style=r["style"],
                                       answer_id=r["answer_id"], typo=False))
        if rng.random() < TYPO_SHARE:
            slipped = typo(r["text"], rng)
            if slipped != r["text"]:
                by_split[split].append(example(item, attr, slipped, q["target"], rng, style=r["style"],
                                               answer_id=r["answer_id"], typo=True))
    return by_split, accepted_by_item


def _says_nothing_about(text: str, attr) -> bool:
    return not _content(text) & set().union(*(_content(o.answer) for o in attr.options), _content(attr.question))


def _none_examples(split: str, want: int, accepted_by_item, items, rng) -> list[dict]:
    """Up to `want` answers about another attribute of the same item, asked against one they do not answer."""
    out = []
    pool = [(r, s) for key in sorted(accepted_by_item) for r, s in accepted_by_item[key]
            if s == split and r["style"] != "extra"]
    rng.shuffle(pool)
    for r, _ in pool:
        if len(out) >= want:
            break
        q = r["request"]
        item = items[q["item"]]
        others = [a for a in item.attributes.values() if a.name != q["attribute"]]
        if not others:
            continue
        attr = rng.choice(others)
        if _says_nothing_about(r["text"], attr):
            out.append(example(item, attr, r["text"], None, rng, style=r["style"], answer_id=r["answer_id"],
                               typo=False, answers_attr=q["attribute"]))
    return out


def parse_examples() -> tuple[dict[str, list[dict]], dict]:
    items = load_items()
    _, rows, problems = answers("parse")
    if problems:
        raise SystemExit(f"{len(problems)} format problems in the raw batches, e.g. {problems[:3]}")
    reviews = read_reviews("parse", "parse_r2")
    rng = random.Random(SEED)
    stats = Counter()
    by_split, accepted_by_item = _answer_examples(rows, reviews, items, rng, stats)
    for split, exs in list(by_split.items()):           # "none" examples, NONE_SHARE of each split
        exs += _none_examples(split, int(len(exs) * NONE_SHARE / (1 - NONE_SHARE)), accepted_by_item, items, rng)
    for split, exs in by_split.items():
        rng.shuffle(exs)
        stats[f"{split}: examples"] = len(exs)
        stats[f"{split}: none"] = sum(e["option"] is None for e in exs)
        stats[f"{split}: typo"] = sum(e["typo"] for e in exs)
    return by_split, dict(sorted(stats.items()))


def main() -> None:
    by_split, stats = parse_examples()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for split in ("train", "val", "test_seen", "test_heldout"):
        # the base lines first and unchanged, so buyers.datagen.is_current still recognises the set
        with open(OUT_DIR / f"{split}.jsonl", "w", encoding="utf-8") as out:
            with open(BASE_DIR / f"{split}.jsonl", encoding="utf-8") as src:
                shutil.copyfileobj(src, out)
            for ex in by_split.get(split, []):
                out.write(json.dumps(ex, ensure_ascii=False) + "\n")
    shutil.copy(BASE_DIR / "scenes.jsonl", OUT_DIR / "scenes.jsonl")
    meta = json.loads((BASE_DIR / "meta.json").read_text())
    meta.update({"tasks": ["ask", "react", "refuse", "parse"], "based_on": "buyers_v6_base",
                 "parse": {"typo_share": TYPO_SHARE, "none_share": NONE_SHARE, "seed": SEED}})
    (OUT_DIR / "meta.json").write_text(json.dumps(meta) + "\n")
    (OUT_DIR / "parse_stats.json").write_text(json.dumps(stats, indent=1) + "\n")
    print(json.dumps(stats, indent=1))


if __name__ == "__main__":
    main()
